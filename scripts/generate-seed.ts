/**
 * Writes supabase/seed.sql: the rooms, product types, fictional retailers and
 * sample products, ready to paste into the Supabase SQL editor (or run with
 * `supabase db reset`). Safe to run more than once: it updates existing rows.
 *
 *   npm run seed
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { CATEGORIES, generateCatalog, RETAILERS, SUBCATEGORIES } from '../src/data/sample/catalog';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: readonly string[]) => (xs.length ? `array[${xs.map(q).join(', ')}]` : `'{}'::text[]`);

const lines: string[] = [
  '-- Generated by scripts/generate-seed.ts. Do not edit by hand; run `npm run seed`.',
  '-- Fictional sample catalog (made-up stores on *.example.com).',
  'begin;',
  '',
  'insert into public.categories (id, label, sort_order) values',
  CATEGORIES.map((c) => `  (${q(c.id)}, ${q(c.label)}, ${c.sortOrder})`).join(',\n'),
  'on conflict (id) do update set label = excluded.label, sort_order = excluded.sort_order;',
  '',
  'insert into public.subcategories (id, category_id, label, sort_order) values',
  SUBCATEGORIES.map((s) => `  (${q(s.id)}, ${q(s.categoryId)}, ${q(s.label)}, ${s.sortOrder})`).join(',\n'),
  'on conflict (id) do update set category_id = excluded.category_id, label = excluded.label, sort_order = excluded.sort_order;',
  '',
  'insert into public.retailers (id, name, domain) values',
  RETAILERS.map((r) => `  (${q(r.id)}, ${q(r.name)}, ${q(r.domain)})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name, domain = excluded.domain;',
  '',
  'insert into public.products (id, category_id, subcategory_id, retailer_id, title, brand, description, price_cents, currency, image_urls, product_url, style_tags, material, color, created_at, external_id) values',
  generateCatalog()
    .map(
      (p) =>
        `  (${[
          q(p.id),
          q(p.categoryId),
          q(p.subcategoryId),
          q(p.retailerId),
          q(p.title),
          q(p.brand),
          q(p.description),
          String(p.priceCents),
          q(p.currency),
          arr(p.imageUrls),
          q(p.productUrl),
          arr(p.styleTags),
          q(p.material),
          q(p.color),
          q(p.createdAt),
          q(p.id),
        ].join(', ')})`,
    )
    .join(',\n'),
  `on conflict (id) do update set
  category_id = excluded.category_id, subcategory_id = excluded.subcategory_id, retailer_id = excluded.retailer_id,
  title = excluded.title, brand = excluded.brand, description = excluded.description,
  price_cents = excluded.price_cents, currency = excluded.currency, image_urls = excluded.image_urls,
  product_url = excluded.product_url, style_tags = excluded.style_tags, material = excluded.material,
  color = excluded.color, is_active = true, updated_at = now();`,
  '',
  'commit;',
  '',
];

const out = join(__dirname, '..', 'supabase', 'seed.sql');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}`);
