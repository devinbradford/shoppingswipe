/// <reference types="node" />
/**
 * Writes supabase/dashboard/waitlist-signup.ts: the waitlist Edge Function as
 * ONE self-contained file, for pasting into the Supabase dashboard editor
 * (Edge Functions > Deploy a new function > Via Editor) instead of deploying
 * with the CLI. Generated from supabase/functions/waitlist-signup/{handler,index}.ts,
 * so never edit the output by hand.
 *
 *   npm run bundle-waitlist
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
const fnDir = join(root, 'supabase', 'functions', 'waitlist-signup');

const handler = readFileSync(join(fnDir, 'handler.ts'), 'utf8')
  // Everything lives in one module, so nothing needs exporting.
  .replace(/^export (?=(async function|function|const|interface|type) )/gm, '');

const index = readFileSync(join(fnDir, 'index.ts'), 'utf8').replace(
  /^import \{[^}]*\} from '\.\/handler\.ts';\n/m,
  '',
);

if (index.includes("from './handler.ts'")) throw new Error('could not strip the handler import from index.ts');

const out = [
  '// CureAvo waitlist Edge Function: single-file version for the Supabase dashboard editor.',
  '// GENERATED by scripts/bundle-waitlist-function.ts from supabase/functions/waitlist-signup.',
  '// Do not edit here; edit those files and run `npm run bundle-waitlist`.',
  '// Name the function exactly: waitlist-signup. Turn OFF "Verify JWT" for it.',
  '',
  '// ===== handler.ts =====',
  handler.trim(),
  '',
  '// ===== index.ts =====',
  index.trim(),
  '',
  '// Makes this file a module, so the Deno declaration above stays local.',
  'export {};',
  '',
].join('\n');

mkdirSync(join(root, 'supabase', 'dashboard'), { recursive: true });
writeFileSync(join(root, 'supabase', 'dashboard', 'waitlist-signup.ts'), out);
console.log('Wrote supabase/dashboard/waitlist-signup.ts');
