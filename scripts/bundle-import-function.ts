/// <reference types="node" />
/**
 * Writes supabase/dashboard/import-feeds.ts: the nightly import Edge Function as ONE
 * self-contained file (the import engine from src/feeds included), for pasting into the
 * Supabase dashboard editor (Edge Functions > Deploy a new function > Via Editor).
 * Generated from supabase/functions/import-feeds, so never edit the output by hand.
 *
 *   npm run bundle-import
 */
import { buildSync } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(__dirname, '..');
const result = buildSync({
  entryPoints: [join(root, 'supabase', 'functions', 'import-feeds', 'index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  write: false,
  legalComments: 'none',
  logLevel: 'error',
  // Built into the Supabase (Deno) runtime.
  external: ['node:*'],
});
const code = result.outputFiles[0].text;
const out = [
  '// CureAvo nightly product import: single-file version for the Supabase dashboard editor.',
  '// GENERATED by scripts/bundle-import-function.ts from supabase/functions/import-feeds and src/feeds.',
  '// Do not edit here; edit those files and run `npm run bundle-import`.',
  '// Name the function exactly: import-feeds. Turn OFF "Verify JWT" for it (it checks IMPORT_FEEDS_SECRET).',
  '// @ts-nocheck',
  '',
  code,
].join('\n');
mkdirSync(join(root, 'supabase', 'dashboard'), { recursive: true });
writeFileSync(join(root, 'supabase', 'dashboard', 'import-feeds.ts'), out);
console.log(`Wrote supabase/dashboard/import-feeds.ts (${Math.round(out.length / 1024)} KB)`);
